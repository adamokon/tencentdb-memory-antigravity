#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { loadConfig, pluginRoot } from './config.mjs'
import { TamClient } from './tam-client.mjs'

const config = loadConfig()
const checks = []
function check(name, ok, detail) { checks.push({ name, ok, detail }) }

check('Node.js', Number(process.versions.node.split('.')[0]) >= 20, process.versions.node)
check('config.env', fs.existsSync(path.join(pluginRoot, 'config.env')), path.join(pluginRoot, 'config.env'))
check('hooks.json', fs.existsSync(path.join(pluginRoot, 'hooks.json')), 'generated by install.sh')
check('mcp_config.json', fs.existsSync(path.join(pluginRoot, 'mcp_config.json')), 'generated by install.sh')

try {
  const client = new TamClient(config)
  const health = await client.health()
  check('Memory Core health', health.ok, `HTTP ${health.status} at ${config.baseUrl}`)
  try {
    await client.readCore()
    check('v3 scoped read access', true, `${config.teamId}/${config.agentId}/${config.userId}`)
  } catch (error) {
    check('v3 scoped read access', false, error.message)
  }
} catch (error) {
  check('Memory Core configuration', false, error.message)
}

for (const item of checks) console.log(`${item.ok ? 'OK  ' : 'FAIL'} ${item.name}: ${item.detail}`)
if (checks.some(item => !item.ok)) process.exitCode = 1
